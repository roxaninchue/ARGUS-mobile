#!/usr/bin/env node
// P0-SH-02: generates app/src/main/java/com/blaze/assistant/ui/argus/icons/LucidePaths.kt (pure data, no Compose)
// from A-team's app/www/icons.js (Lucide v0.460.0 path data, ISC) plus, for the 04 §2.7 icons A-team doesn't ship,
// the same Lucide release's lucide-static SVGs.
//
//   node tools/gen-lucide.mjs --icons <a-team>/app/www/icons.js --lucide <lucide-static@0.460.0>/icons [--out <file>]
//
// Every SVG element (path, circle, line, rect, polyline, polygon) becomes one SVG path string in the 24×24 viewBox.
// Output is sorted by name and has no timestamp, so the same inputs always give the same file (LucidePathsTest checks
// the shape; run it twice and diff to check determinism).
import fs from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, all) => (v.startsWith('--') ? a.concat([[v.slice(2), all[i + 1]]]) : a), []));
const OUT = args.out || 'app/src/main/java/com/blaze/assistant/ui/argus/icons/LucidePaths.kt';
const LUCIDE_VERSION = '0.460.0';

// 04 §2.7 key icon semantics: every one must exist in the output.
export const REQUIRED = ['bot', 'message-circle', 'bell', 'plus', 'search', 'brain', 'scroll-text', 'cpu', 'blocks', 'monitor', 'repeat',
  'list-checks', 'library', 'shield-check', 'users', 'workflow', 'square-terminal', 'globe', 'cloud', 'mic', 'audio-lines', 'hand', 'flag',
  'sparkles', 'heart-pulse', 'wallet', 'briefcase', 'house', 'graduation-cap', 'plane', 'palette', 'notebook-pen', 'smartphone'];

const n = s => {
  const v = Number(s);
  if (!Number.isFinite(v)) throw new Error('bad number ' + s);
  return +v.toFixed(4);
};
const attrs = tag => Object.fromEntries([...tag.matchAll(/([a-z][a-z0-9-]*)="([^"]*)"/g)].map(m => [m[1], m[2]]));

function toPath(el, a) {
  switch (el) {
    case 'path': return a.d;
    case 'line': return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case 'circle': { const cx = n(a.cx), cy = n(a.cy), r = n(a.r); return `M${n(cx - r)} ${cy}a${r} ${r} 0 1 0 ${n(2 * r)} 0a${r} ${r} 0 1 0 ${n(-2 * r)} 0z`; }
    case 'ellipse': { const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry); return `M${n(cx - rx)} ${cy}a${rx} ${ry} 0 1 0 ${n(2 * rx)} 0a${rx} ${ry} 0 1 0 ${n(-2 * rx)} 0z`; }
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/).map(n);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return el === 'polygon' ? d + 'z' : d;
    }
    case 'rect': {
      const x = n(a.x || 0), y = n(a.y || 0), w = n(a.width), h = n(a.height);
      let rx = a.rx != null ? n(a.rx) : a.ry != null ? n(a.ry) : 0;
      let ry = a.ry != null ? n(a.ry) : rx;
      rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${n(-w)}z`;
      return `M${n(x + rx)} ${y}h${n(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${n(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${n(-rx)} ${ry}` +
        `h${n(-(w - 2 * rx))}a${rx} ${ry} 0 0 1 ${n(-rx)} ${n(-ry)}v${n(-(h - 2 * ry))}a${rx} ${ry} 0 0 1 ${rx} ${n(-ry)}z`;
    }
    default: throw new Error('unsupported element ' + el);
  }
}

function svgToPaths(svg) {
  const out = [];
  for (const m of svg.matchAll(/<(path|line|circle|ellipse|polyline|polygon|rect)\b([^>]*?)\/?>/g)) out.push(toPath(m[1], attrs(m[2])));
  return out;
}

// --- A-team icons.js: `"name": "<svg body>",` lines inside const ICONS = { ... }; aliases after it.
const src = fs.readFileSync(args.icons, 'utf8');
const body = src.slice(src.indexOf('const ICONS = {'), src.indexOf('\n};', src.indexOf('const ICONS = {')));
const icons = new Map();
for (const m of body.matchAll(/^\s*"([a-z0-9-]+)":\s*("(?:[^"\\]|\\.)*")\s*,?\s*$/gm)) icons.set(m[1], svgToPaths(JSON.parse(m[2])));
const aliases = new Map();
for (const m of src.matchAll(/ICONS\[?['.]?([a-z0-9-]+)'?\]?\s*=\s*ICONS(?:\['([a-z0-9-]+)'\]|\.([a-z0-9]+))/g)) aliases.set(m[1], m[2] || m[3]);

// --- lucide-static for the required names A-team lacks
const extra = [];
for (const name of REQUIRED) {
  if (icons.has(name)) continue;
  if (!args.lucide) throw new Error(`"${name}" is not in icons.js; pass --lucide <lucide-static@${LUCIDE_VERSION}/icons>`);
  const f = path.join(args.lucide, name + '.svg');
  const svg = fs.readFileSync(f, 'utf8');
  if (!svg.includes(`lucide-static v${LUCIDE_VERSION}`)) throw new Error(`${f} is not lucide-static ${LUCIDE_VERSION}`);
  icons.set(name, svgToPaths(svg));
  extra.push(name);
}
for (const name of REQUIRED) if (!icons.get(name)?.length) throw new Error('missing ' + name);

const kq = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$') + '"';
const names = [...icons.keys()].sort();
let kt = `package com.blaze.assistant.ui.argus.icons

// GENERATED by tools/gen-lucide.mjs — do not edit. Lucide v${LUCIDE_VERSION} (https://lucide.dev), ISC License,
// Copyright (c) Lucide Contributors (portions Feather, MIT, Cole Bemis). Source: A-team app/www/icons.js
// (${names.length - extra.length} icons) + lucide-static ${LUCIDE_VERSION} (${extra.length}: ${extra.join(', ')}).

/** Each icon as SVG path strings in Lucide's 24×24 viewBox (stroke-only, round caps and joins). */
object LucidePaths {
    const val VERSION = "${LUCIDE_VERSION}"
    const val VIEWPORT = 24f

    val ICONS: Map<String, List<String>> = linkedMapOf(
`;
kt += names.map(k => `        ${kq(k)} to listOf(${icons.get(k).map(kq).join(', ')}),`).join('\n') + '\n    )\n\n';
const al = [...aliases.entries()].filter(([, t]) => icons.has(t)).sort((a, b) => a[0].localeCompare(b[0]));
kt += `    /** A-team's friendlier names. */\n    val ALIASES: Map<String, String> = linkedMapOf(${al.map(([a, t]) => `${kq(a)} to ${kq(t)}`).join(', ')})\n}\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, kt);
console.log(`wrote ${OUT}: ${names.length} icons (${extra.length} from lucide-static), ${al.length} aliases`);
