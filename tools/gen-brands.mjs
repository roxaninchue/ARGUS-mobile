#!/usr/bin/env node
// Model picker brand marks (owner, 13 Nov 2026: "change the icons to the provider original icons").
// Generates app/src/main/java/com/blaze/assistant/brand/BrandPaths.kt (pure data, no Compose; outside ui/ so the
// maker ids are not UI strings for HideModels19Test) from
// @lobehub/icons-static-svg (MIT). A brand's "-color" SVG is used when it has only solid fills; otherwise (gradients, shapes other than paths, or
// no color file) its mono SVG with one brand colour from FALLBACK, or no colour (= drawn in ink) when FALLBACK has none.
//
//   npm pack @lobehub/icons-static-svg && tar xzf lobehub-icons-static-svg-*.tgz
//   node tools/gen-brands.mjs --icons package/icons [--out <file>]
//
// Sorted, no timestamp: the same inputs always give the same file. Logos are their owners' trademarks, shown only to
// name the model maker in the picker.
import fs from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, all) => (v.startsWith('--') ? a.concat([[v.slice(2), all[i + 1]]]) : a), []));
const OUT = args.out || 'app/src/main/java/com/blaze/assistant/brand/BrandPaths.kt';
const DIR = args.icons;
if (!DIR) throw new Error('--icons <dir> required');

export const BRANDS = ['baidu', 'bytedance', 'cerebras', 'claude', 'cohere', 'deepseek', 'doubao', 'gemini', 'gemma', 'grok', 'hunyuan',
  'kimi', 'meta', 'minimax', 'mistral', 'moonshot', 'nvidia', 'openai', 'qwen', 'stepfun', 'xiaomimimo', 'zhipu'];
const FALLBACK = { gemini: '#3186FF', hunyuan: '#0055E9', gemma: '#4285F4', meta: '#0082FB', minimax: '#F23F5D', stepfun: '#005AFF' };

const attrs = tag => Object.fromEntries([...tag.matchAll(/([a-z][a-z-]*)="([^"]*)"/g)].map(m => [m[1], m[2]]));
const argb = hex => { let h = hex.replace('#', ''); if (h.length === 3) h = h.split('').map(c => c + c).join(''); return '0xFF' + h.toUpperCase(); };

// 0.53.2 (owner, 14 Nov 2026: "these icons aren't the real thing"): the SVGs write arc flags packed ("a1 1 0 01-4 2" =
// flags 0,1 then x -4), which Android's path parser misreads (Gemini drew as a sliver, MiMo's letters broke). Every
// path is re-written with each number spelled out, and each keeps its own fill rule (DeepSeek and Zhipu are nonzero;
// drawing them even-odd punched holes in them).
const ARGS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, a: 7, z: 0 };
export function normalize(d) {
  const out = []; let i = 0, cmd = null, n = 0;
  const num = () => { const m = /^[+-]?(\d+\.?\d*|\.\d+)(e[+-]?\d+)?/i.exec(d.slice(i)); if (!m) throw new Error('bad path at ' + i + ': ' + d.slice(i, i + 20)); i += m[0].length; return m[0]; };
  const skip = () => { while (i < d.length && /[\s,]/.test(d[i])) i++; };
  for (skip(); i < d.length; skip()) {
    if (/[a-z]/i.test(d[i])) { cmd = d[i++]; n = 0; out.push(cmd); if (cmd.toLowerCase() === 'z') cmd = null; continue; }
    if (!cmd) throw new Error('number without command at ' + i);
    const k = ARGS[cmd.toLowerCase()];
    const flag = cmd.toLowerCase() === 'a' && (n % 7 === 3 || n % 7 === 4);
    out.push(flag ? d[i++] : num()); n++;
    if (n % k === 0 && cmd.toLowerCase() === 'm') cmd = cmd === 'm' ? 'l' : 'L';
  }
  return out.join(' ');
}

function paths(file, color) {
  const svg = fs.readFileSync(file, 'utf8');
  if (/<(circle|rect|ellipse|polygon|polyline|line)\b/.test(svg)) throw new Error('non-path element in ' + file);
  const root = attrs(/<svg\b[^>]*>/.exec(svg)[0]);
  return [...svg.matchAll(/<path\b[^>]*>/g)].map(m => {
    const a = attrs(m[0]);
    const fill = a.fill && a.fill.startsWith('#') ? argb(a.fill) : color;
    return { d: normalize(a.d), fill, evenOdd: (a['fill-rule'] || root['fill-rule']) === 'evenodd' };
  });
}

const out = [];
for (const b of [...BRANDS].sort()) {
  const col = path.join(DIR, b + '-color.svg');
  const solid = fs.existsSync(col) && !/Gradient|url\(|<(circle|rect|ellipse|polygon|polyline|line|g)\b|transform=/.test(fs.readFileSync(col, 'utf8'));
  const ps = solid ? paths(col, null) : paths(path.join(DIR, b + '.svg'), FALLBACK[b] ? argb(FALLBACK[b]) : null);
  if (!ps.length) throw new Error('no paths for ' + b);
  out.push(`        "${b}" to listOf(\n` + ps.map(p => `            BrandPath("${p.d}", ${p.fill ? p.fill + 'L' : 'null'}${p.evenOdd ? ', evenOdd = true' : ''}),`).join('\n') + `\n        ),`);
}

const kt = `package com.blaze.assistant.brand

// GENERATED by tools/gen-brands.mjs from @lobehub/icons-static-svg (MIT). Do not edit by hand.
// Logos are trademarks of their owners; used only to name the model maker in the model picker.

/** One filled path in a 24×24 viewBox ([d] with every number spelled out). [argb] null = draw in the current ink colour; [evenOdd] = the SVG's fill-rule. */
data class BrandPath(val d: String, val argb: Long?, val evenOdd: Boolean = false)

object BrandPaths {
    const val VIEWPORT = 24f
    val ICONS: Map<String, List<BrandPath>> = mapOf(
${out.join('\n')}
    )
}
`;
fs.writeFileSync(OUT, kt);
console.log('wrote', OUT, BRANDS.length, 'brands');
