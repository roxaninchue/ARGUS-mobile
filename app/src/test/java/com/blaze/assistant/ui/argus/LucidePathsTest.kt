package com.blaze.assistant.ui.argus

import com.blaze.assistant.ui.argus.icons.LucidePaths
import com.blaze.assistant.ui.argus.icons.LucideSpec
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * P0-SH-02: the generated Lucide set. Shape checks on tools/gen-lucide.mjs's output (sorted, versioned, every 04 §2.7
 * icon present, path data well-formed and inside the 24-unit box). Determinism: running the generator twice gives the
 * same bytes (checked when it was generated; the header has no timestamp, which this test pins).
 */
class LucidePathsTest {
    private val root = listOf(File("src/main/java"), File("app/src/main/java")).firstOrNull { it.isDirectory }

    @Test fun everySemanticAndDomainIconExists() {
        for (n in LucideSpec.Semantic.ALL + LucideSpec.DOMAIN.values) assertTrue(n, LucidePaths.ICONS.containsKey(n))
        assertTrue(LucidePaths.ICONS.size >= 90)
        assertTrue(LucidePaths.ICONS.containsKey(LucideSpec.FALLBACK))
    }

    @Test fun sortedAndVersioned() {
        assertEquals(LucidePaths.ICONS.keys.sorted(), LucidePaths.ICONS.keys.toList())
        assertEquals("0.460.0", LucidePaths.VERSION)
        root?.let {
            val head = File(it, "com/blaze/assistant/ui/argus/icons/LucidePaths.kt").readText().lines().take(6).joinToString("\n")
            assertTrue(head.contains("GENERATED by tools/gen-lucide.mjs") && head.contains("ISC License"))
            assertTrue("no timestamp in the generated header", !Regex("""20\d\d-\d\d-\d\d""").containsMatchIn(head))
        }
    }

    @Test fun pathDataIsWellFormed() {
        val ok = Regex("""^[MmLlHhVvCcSsQqTtAaZz0-9.,\s\-]+$""")
        val num = Regex("""-?\d*\.?\d+(?:e-?\d+)?""")
        for ((name, paths) in LucidePaths.ICONS) {
            assertTrue(name, paths.isNotEmpty())
            for (d in paths) {
                assertTrue("$name: $d", ok.matches(d) && d.trimStart().first() in "Mm")
                // absolute coordinates stay in a generous 24-unit box
                assertTrue("$name: $d", num.findAll(d).all { it.value.toDouble() in -25.0..25.0 })
            }
        }
    }

    @Test fun aliasesAndFallback() {
        assertEquals("triangle-alert", LucideSpec.resolve("alert-triangle"))
        assertEquals("trash-2", LucideSpec.resolve("trash"))
        assertEquals("bot", LucideSpec.resolve(" Bot "))
        assertEquals(LucideSpec.FALLBACK, LucideSpec.resolve("no-such-icon"))
    }

    @Test fun strokeFollowsSizeLikeATeam() {
        assertEquals(2.25f, LucideSpec.strokeFor(LucideSpec.Size.CHIP), 0f)
        assertEquals(2.25f, LucideSpec.strokeFor(LucideSpec.Size.TOOL), 0f)
        assertEquals(2f, LucideSpec.strokeFor(LucideSpec.Size.ICON_BUTTON), 0f)
        assertEquals(1.85f, LucideSpec.strokeFor(LucideSpec.Size.BACK), 0f)
    }

    @Test fun newUiUsesLucideNotMaterialIcons() {
        val dir = root?.let { File(it, "com/blaze/assistant/ui/argus") } ?: return
        val hits = dir.walkTopDown().filter { it.isFile && it.extension == "kt" }.filter { "material.icons" in it.readText() }.map { it.name }.toList()
        assertTrue("Material icons in ui/argus: $hits", hits.isEmpty())
    }
}
